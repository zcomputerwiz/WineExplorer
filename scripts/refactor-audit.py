"""Inventory committed Wine changes against a real upstream tag, including modes.

The external bare repository must contain the upstream tag and the project's
commit (fetch the latter into refs/audit/wineexplorer). No working files are read.
Classification is deliberately separate from evidence; suggestions are not review.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess


def git(repository, *args):
    return subprocess.check_output(["git", f"--git-dir={repository}", *args])


def tree(repository, revision):
    entries = {}
    for item in git(repository, "ls-tree", "-rz", revision).split(b"\0"):
        if not item:
            continue
        metadata, path = item.split(b"\t", 1)
        mode, kind, oid = metadata.decode().split()
        entries[path.decode("utf-8")] = {"mode": mode, "kind": kind, "oid": oid}
    return entries


def sha(data):
    return hashlib.sha256(data).hexdigest()


def classify(repository, record, modules, assets):
    """Classify mechanically provable cases; leave stock edits for hunk review."""
    path = record["path"]
    before, after = record["before"], record["after"]
    if record["mode_only"]:
        return {"class": "N", "change": "Executable-bit import noise",
                "target": "Restore tag mode; no content patch", "review": "proven"}
    if record["upstream_blob_known"] or record["upstream_deletion_known"]:
        return {"class": "B", "change": "Exact upstream post-tag file version",
                "target": "wineexplorer/11.19: retain upstream provenance; drop on rebase",
                "review": "proven"}
    if before and after and path in {
            "dlls/ws2_32/hosts", "dlls/ws2_32/networks",
            "dlls/ws2_32/protocol", "dlls/ws2_32/services"}:
        old = git(repository, "cat-file", "blob", before["oid"])
        new = git(repository, "cat-file", "blob", after["oid"])
        if old.replace(b"\r\n", b"\n") == new.replace(b"\r\n", b"\n"):
            return {"class": "N", "change": "CRLF/LF import normalization only",
                    "target": "Restore tag bytes; no behavior patch", "review": "proven"}
    module = "/".join(path.split("/")[:2])
    if module in modules:
        return {"class": "M", "change": "Project module or replacement module",
                "target": "src/" + module, "review": "module-boundary"}
    if path.startswith("programs/explorer/") and not before:
        return {"class": "M", "change": "New shell source/resource",
                "target": "src/dlls/wexshell (P3), then P3b seams",
                "review": "module-boundary"}
    if path == "include/wexhost.h":
        return {"class": "M", "change": "Project bridge public header",
                "target": "src/include/wexhost.h; assemble into include/",
                "review": "module-boundary"}
    if path.startswith("resources/themes/"):
        return {"class": "M", "change": "Project-authored theme definitions",
                "target": "src/resources/themes; assemble into resources/themes/",
                "review": "module-boundary"}
    if path in assets:
        return {"class": "X", "change": "Open replacement art: " + assets[path],
                "target": "wineexplorer/11.19: open resource substitutions",
                "review": "asset-manifest"}
    return {"class": "?", "change": "Stock modification: hunk review pending",
            "target": "Not yet assigned", "review": "pending"}


def write_map(repository, result, output, assets_path, reviews_path):
    old = tree(repository, result["revisions"]["baseline"])
    new = tree(repository, result["revisions"]["source"] + ":wine")
    old_modules = {"/".join(path.split("/")[:2]) for path in old
                   if path.startswith(("dlls/", "programs/"))}
    new_modules = {"/".join(path.split("/")[:2]) for path in new
                   if path.startswith(("dlls/", "programs/"))}
    # Explicit replacement modules named in the work order; keep their Wine notices.
    modules = new_modules - old_modules | {
        "dlls/desk.cpl", "dlls/wlanui", "programs/wmplayer"}
    assets = {entry["path"].removeprefix("wine/"): entry["source"]
              for entry in json.loads(assets_path.read_text(encoding="utf-8"))}
    reviews = json.loads(reviews_path.read_text(encoding="utf-8")) if reviews_path.exists() else {}
    unknown = set(reviews) - {record["path"] for record in result["files"]}
    if unknown:
        raise ValueError(f"Review paths absent from inventory: {sorted(unknown)}")
    classified = []
    lines = ["# Wine refactor path inventory", "",
             "Generated by `scripts/refactor-audit.py --map`. Paths are relative to `wine/`.",
             "`?` means unreviewed; P0 acceptance has **not** passed while any remain.",
             "For proven whole-file changes, the classification covers all hunks and metadata.",
             "Mixed stock files require explicit per-hunk decisions in the main map.", "",
             "| File | Change | Class | Target branch/location | Hunks |",
             "|---|---|---|---|---|"]
    for record in result["files"]:
        decision = classify(repository, record, modules, assets)
        hunk_decisions = []
        if record["path"] in reviews:
            reviewed = reviews[record["path"]]
            if reviewed["patch_sha256"] != record["patch_sha256"]:
                raise ValueError("Reviewed patch changed: " + record["path"])
            decision = {key: reviewed[key] for key in ("class", "change", "target", "review")}
            if "hunks" in reviewed:
                hunk_decisions = reviewed["hunks"]
                if [item["sha256"] for item in hunk_decisions] != [item["sha256"] for item in record["hunks"]]:
                    raise ValueError("Reviewed hunks changed: " + record["path"])
                decision["class"] = "/".join(sorted({item["class"] for item in hunk_decisions} or {decision["class"]}))
        classified.append({"path": record["path"],
                           "patch_sha256": record["patch_sha256"],
                           "hunk_sha256": [hunk["sha256"] for hunk in record["hunks"]],
                           "hunk_decisions": hunk_decisions,
                           **decision})
        cells = ["`" + record["path"] + "`", decision["change"], decision["class"],
                 decision["target"], str(len(record["hunks"]))]
        lines.append("| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    output.with_suffix(".json").write_text(json.dumps({
        "revisions": result["revisions"], "patch_sha256": result["patch_sha256"],
        "files": classified}, indent=2) + "\n", encoding="utf-8")
    details = ["", "## Reviewed stock hunks", "",
               "| File | Hunk | Class | Change | Target |", "|---|---|---|---|---|"]
    for row in classified:
        for item in row["hunk_decisions"]:
            cells = ["`" + row["path"] + "`", "`" + item["header"] + "`",
                     item["class"], item["change"], item["target"]]
            details.append("| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |")
    if len(details) > 5:
        output.write_text(output.read_text(encoding="utf-8") + "\n".join(details) + "\n", encoding="utf-8")
    print("Classification memberships:", {key: sum(key in row["class"].split("/") for row in classified)
                                     for key in ("U", "X", "H", "M", "B", "N", "?")})


def inventory(repository, baseline, source, imported, master):
    revisions = {
        "baseline": git(repository, "rev-parse", f"{baseline}^{{commit}}").decode().strip(),
        "source": git(repository, "rev-parse", f"{source}^{{commit}}").decode().strip(),
        "import": git(repository, "rev-parse", f"{imported}^{{commit}}").decode().strip(),
        "fork_master": git(repository, "rev-parse", f"{master}^{{commit}}").decode().strip(),
    }
    old = tree(repository, revisions["baseline"])
    new = tree(repository, revisions["source"] + ":wine")
    initial = tree(repository, revisions["import"] + ":wine")
    upstream = tree(repository, revisions["fork_master"])
    upstream_objects = set()
    history = git(repository, "log", "--format=", "--raw", "--no-abbrev",
                  "--no-renames", revisions["fork_master"],
                  "^" + revisions["baseline"])
    for line in history.decode().splitlines():
        if line.startswith(":"):
            metadata, path = line.split("\t", 1)
            fields = metadata.split()
            upstream_objects.add((path, fields[2]))
            upstream_objects.add((path, fields[3]))
    patch = git(repository, "diff", "--no-ext-diff", "--no-renames", "--binary",
                revisions["baseline"], revisions["source"] + ":wine", "--")
    blocks = {}
    for block in re.split(br"(?=^diff --git )", patch, flags=re.M):
        if not block:
            continue
        first = block.split(b"\n", 1)[0].decode()
        # Wine paths have no quoted/non-ASCII names; fail instead of misindexing.
        match = re.fullmatch(r"diff --git a/(.+) b/\1", first)
        if not match:
            raise ValueError(f"Unsupported patch path: {first}")
        blocks[match[1]] = block
    records = []
    for path in sorted(set(old) | set(new)):
        before, after = old.get(path), new.get(path)
        if before == after:
            continue
        block = blocks.pop(path)
        hunks = []
        for hunk in re.split(br"(?=^@@ )", block, flags=re.M)[1:]:
            lines = hunk.splitlines()
            hunks.append({"header": lines[0].decode("utf-8", "replace"),
                          "sha256": sha(hunk),
                          "added": sum(line.startswith(b"+") for line in lines[1:]),
                          "removed": sum(line.startswith(b"-") for line in lines[1:])})
        mode_only = bool(before and after and before["oid"] == after["oid"])
        inherited = after == initial.get(path)
        present_upstream = after == upstream.get(path)
        records.append({"path": path, "before": before, "after": after,
                        "import": initial.get(path), "fork_master": upstream.get(path),
                        "mode_only": mode_only, "unchanged_since_import": inherited,
                        "matches_fork_master": present_upstream,
                        "upstream_blob_known": bool(after and
                            ((path, after["oid"]) in upstream_objects or
                             (upstream.get(path) and after["oid"] == upstream[path]["oid"]))),
                        "upstream_deletion_known": bool(not after and path not in upstream and
                            (path, "0" * 40) in upstream_objects),
                        "patch_sha256": sha(block), "patch_lines": len(block.splitlines()),
                        "hunks": hunks})
    if blocks:
        raise ValueError(f"Unaccounted patch blocks: {list(blocks)}")
    if sum(record["patch_lines"] for record in records) != len(patch.splitlines()):
        raise ValueError("Patch line coverage is incomplete")
    return {"schema": 1, "revisions": revisions, "patch_sha256": sha(patch),
            "patch_lines": len(patch.splitlines()), "files": records}, patch


def check_map(result, path, require_classified):
    mapped = json.loads(path.read_text(encoding="utf-8"))
    if mapped["revisions"] != result["revisions"] or mapped["patch_sha256"] != result["patch_sha256"]:
        raise SystemExit("Map belongs to a different audited snapshot")
    rows = {row["path"]: row for row in mapped["files"]}
    if len(rows) != len(mapped["files"]):
        raise SystemExit("Duplicate paths in map")
    if set(rows) != {row["path"] for row in result["files"]}:
        raise SystemExit("Map has missing or extra paths")
    pending = 0
    for record in result["files"]:
        row = rows[record["path"]]
        if (row["patch_sha256"] != record["patch_sha256"] or
                row["hunk_sha256"] != [hunk["sha256"] for hunk in record["hunks"]]):
            raise SystemExit("Map hunk coverage changed: " + record["path"])
        if not set(row["class"].split("/")) <= {"U", "X", "H", "M", "B", "N", "?"} or not row["target"]:
            raise SystemExit("Invalid classification: " + record["path"])
        decisions = row.get("hunk_decisions", [])
        missing_decisions = bool(record["hunks"] and row["review"] == "stock-hunks-reviewed" and not decisions)
        if decisions:
            if [item["sha256"] for item in decisions] != row["hunk_sha256"]:
                raise SystemExit("Incomplete hunk decisions: " + record["path"])
            for item in decisions:
                if item["class"] not in {"U", "X", "H", "M", "B", "N", "?"} or not item["target"]:
                    raise SystemExit("Invalid hunk decision: " + record["path"])
            if set(row["class"].split("/")) != {item["class"] for item in decisions}:
                raise SystemExit("File and hunk classifications disagree: " + record["path"])
        pending += "?" in row["class"].split("/") or row["review"] == "pending" or missing_decisions
    print(f"Map covers all {len(rows)} paths; {pending} need stock-hunk review")
    if require_classified and pending:
        raise SystemExit("P0 acceptance incomplete: unclassified changes remain")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--git-dir", required=True)
    parser.add_argument("--baseline", default="wine-11.19")
    parser.add_argument("--source", default="refs/audit/wineexplorer")
    parser.add_argument("--import", dest="imported", default="40c17e1")
    parser.add_argument("--master", default="master")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--verify", action="store_true",
                        help="Compare regenerated evidence against existing JSON and patch")
    parser.add_argument("--map", type=Path,
                        help="Write a path classification table and JSON coverage index")
    parser.add_argument("--assets", type=Path, default=Path("assets/open_assets.json"))
    parser.add_argument("--reviews", type=Path, default=Path("docs/refactor/REVIEWS.json"),
                        help="Reviewed stock decisions, pinned to exact per-file patches")
    parser.add_argument("--check-map", type=Path, help="Verify complete path and hunk coverage")
    parser.add_argument("--require-classified", action="store_true",
                        help="Fail when the checked map still has unclassified changes")
    args = parser.parse_args()
    if args.require_classified and not args.check_map:
        parser.error("--require-classified needs --check-map")
    result, patch = inventory(args.git_dir, args.baseline, args.source,
                              args.imported, args.master)
    json_path = args.output.with_suffix(".json")
    patch_path = args.output.with_suffix(".patch")
    if args.verify:
        if json.loads(json_path.read_text(encoding="utf-8")) != result:
            raise SystemExit("Inventory changed: source or baseline differs")
        if patch_path.read_bytes() != patch:
            raise SystemExit("Saved patch does not match Git objects")
    else:
        json_path.parent.mkdir(parents=True, exist_ok=True)
        json_path.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
        patch_path.write_bytes(patch)
    if args.map:
        write_map(args.git_dir, result, args.map, args.assets, args.reviews)
    if args.check_map:
        check_map(result, args.check_map, args.require_classified)
    files = result["files"]
    print(json.dumps({"revisions": result["revisions"], "files": len(files),
                      "hunks": sum(len(file["hunks"]) for file in files),
                      "mode_only": sum(file["mode_only"] for file in files),
                      "unchanged_since_import": sum(file["unchanged_since_import"] for file in files),
                      "matches_fork_master": sum(file["matches_fork_master"] for file in files),
                      "patch_lines": result["patch_lines"]}, indent=2))


if __name__ == "__main__":
    main()
