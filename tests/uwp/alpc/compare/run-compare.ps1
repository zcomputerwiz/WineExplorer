<#
.SYNOPSIS
  Runs the probes of probes.txt on the Windows host and under Wine (the owned lab guest) and reports where they differ.

.DESCRIPTION
  For each probe: build it with the mingw cross compiler (WSL), run it on the host, run it in the lab guest, normalise both outputs
  (normalize.py), compare them, and write compare/report.md. The normalised Windows output is the golden file expected/<name>.windows.txt:
  with -UseGolden the host is not needed, Wine is compared with the golden file; with -UpdateGolden the golden files are rewritten from
  the host run (do that only after looking at a change on Windows).

  Exit status: 0 when every probe agrees, 1 when at least one differs, 2 on a tooling failure.

.EXAMPLE
  .\run-compare.ps1                       # host and Wine, golden files checked too
  .\run-compare.ps1 -UseGolden            # Wine against the golden files only (no Windows host needed)
  .\run-compare.ps1 -Only order-probe,peek-probe -UpdateGolden
#>
param(
    [string[]]$Only = @(),
    [switch]$UseGolden,
    [switch]$UpdateGolden,
    [switch]$HostOnly,
    [string]$LabSh = (Join-Path $PSScriptRoot '..\..\..\..\scripts\lab\uwp\lab.sh'),
    [string]$Bash = 'C:\Program Files\Git\bin\bash.exe'
)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$alpc = Split-Path $here -Parent
$build = Join-Path $here 'build'; $out = Join-Path $here 'out'; $exp = Join-Path $here 'expected'
New-Item -ItemType Directory -Force $build, $out, $exp | Out-Null
$wslHere = (wsl wslpath -a ($here -replace '\\', '/')).Trim()
$python = 'python'
if (-not (Get-Command python -ErrorAction SilentlyContinue)) { $python = 'py' }

function Normalize([string]$raw, [string]$extra) {
    $args2 = @((Join-Path $here 'normalize.py'))
    if ($extra) { $args2 += @('--extra', $extra) }
    ($raw -split "`r?`n" -join "`n") | & $python @args2
}

$probes = Get-Content (Join-Path $here 'probes.txt') | Where-Object { $_ -and $_ -notmatch '^\s*#' } | ForEach-Object {
    $p = $_ -split '\|'
    [pscustomobject]@{ Name = $p[0].Trim(); Timeout = [int]$p[1].Trim(); Extra = $p[2].Trim(); What = $p[3].Trim() }
}
$Only = @($Only | ForEach-Object { $_ -split ',' } | Where-Object { $_ })   # -File passes "a,b" as one string
if ($Only.Count) { $probes = @($probes | Where-Object { $Only -contains $_.Name }) }
if (-not $probes) { Write-Host 'no probe selected (check -Only and probes.txt)' -ForegroundColor Red; exit 2 }

$report = @("# Windows / Wine comparison", "", "Generated by run-compare.ps1. Differences are lines of the normalised output that differ.", "")
$bad = 0; $rows = @()
foreach ($p in $probes) {
    $name = $p.Name
    Write-Host "== $name" -ForegroundColor Cyan
    $src = Join-Path $alpc "$name.c"; $exe = Join-Path $build "$name.exe"
    wsl -e bash -c "cd '$wslHere/..' && x86_64-w64-mingw32-gcc -O1 -o 'compare/build/$name.exe' '$name.c' -luser32 -lntdll 2>&1 | head -5"
    if (-not (Test-Path $exe)) { Write-Host "build failed" -ForegroundColor Red; $rows += "| $name | build failed | | |"; $bad++; continue }

    # Windows (or golden)
    $goldenFile = Join-Path $exp "$name.windows.txt"
    if ($UseGolden) {
        $win = if (Test-Path $goldenFile) { Get-Content $goldenFile -Raw } else { $null }
        if ($null -eq $win) { Write-Host "no golden file" -ForegroundColor Yellow; $rows += "| $name | no golden file | | |"; $bad++; continue }
    } else {
        $so = Join-Path $out "$name.windows.raw"
        $pr = Start-Process -FilePath $exe -RedirectStandardOutput $so -PassThru -WindowStyle Hidden
        if (-not $pr.WaitForExit($p.Timeout * 1000)) { $pr.Kill(); Write-Host "host run timed out" -ForegroundColor Yellow }
        $win = (Normalize (Get-Content $so -Raw) $p.Extra) -join "`n"
        $win += "`n"
        if ($UpdateGolden) { [IO.File]::WriteAllText($goldenFile, $win); Write-Host "golden updated" }
    }
    if ($HostOnly) { $rows += "| $name | host only | | |"; continue }

    # Wine in the lab guest
    $pad = Join-Path $env:TEMP 'wex-lab-pad'
    New-Item -ItemType Directory -Force $pad | Out-Null
    Copy-Item $exe (Join-Path $pad "$name.exe") -Force
    Copy-Item (Join-Path $here 'wine-run.sh') (Join-Path $pad 'wine-run.sh') -Force
    $env:LABPAD = ($pad -replace '\\', '/' -replace '^([A-Za-z]):', '/$1').ToLower()   # Git Bash form of the pad directory
    & $Bash $LabSh push "$name.exe" | Out-Null
    & $Bash $LabSh push 'wine-run.sh' | Out-Null
    $wo = Join-Path $out "$name.wine.raw"
    $cmd = "bash /home/debian/uwp-u1-20261111/claude/wine-run.sh $name.exe $($p.Timeout)"
    & $Bash $LabSh wait $cmd ($p.Timeout + 60) 2>&1 | Out-File $wo -Encoding ascii
    $wine = (Normalize (Get-Content $wo -Raw) $p.Extra) -join "`n"; $wine += "`n"
    [IO.File]::WriteAllText((Join-Path $out "$name.wine.txt"), $wine)
    [IO.File]::WriteAllText((Join-Path $out "$name.windows.txt"), $win)

    $diffText = (& $python (Join-Path $here 'diff.py') (Join-Path $out "$name.windows.txt") (Join-Path $out "$name.wine.txt")) -join "`n"
    if ($LASTEXITCODE -eq 0) { Write-Host "same" -ForegroundColor Green; $rows += "| $name | same | $($p.What) | |" }
    else {
        $bad++
        $n = @($diffText -split "`n" | Where-Object { $_ -match '^[-+]' -and $_ -notmatch '^(---|\+\+\+)' }).Count
        Write-Host "DIFFERENT ($n lines)" -ForegroundColor Red
        $rows += "| $name | **different** | $($p.What) | $n lines |"
        $report += "## $name  ($($p.What))", "", '```diff', $diffText, '```', ''
    }
}$head = @("| probe | result | what it checks | differences |", "|---|---|---|---|") + $rows
$report = $report[0..3] + $head + "" + $report[4..($report.Count - 1)]
[IO.File]::WriteAllText((Join-Path $here 'report.md'), ($report -join "`n"))
Write-Host "report: $(Join-Path $here 'report.md')  ($bad probe(s) differ or failed)"
if ($bad) { exit 1 } else { exit 0 }
